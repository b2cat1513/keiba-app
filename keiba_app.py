def preprocess_image_for_ocr(image):
    """画像のコントラスト調整・二値化処理（OCR精度向上）"""
    gray = image.convert("L")
    enhanced = ImageOps.autocontrast(gray, cutoff=2)
    binary = enhanced.point(lambda p: 255 if p > 165 else 0)
    return binary

def parse_umanity_ocr_text(ocr_text):
    """ウマニティ等のOCRテキストから馬名と指数を自動抽出"""
    lines = [line.strip() for line in ocr_text.split("\n") if line.strip()]
    extracted_data = []
    
    # 馬名と数字（指数）のパターンマッチング
    pattern = re.compile(r"([1-9]|1[0-8])?\s*([一-龠ぁ-んァ-ヶーa-zA-Z0-9]{2,10})\s*(\d{2,3}(?:\.\d)?)")
    
    for line in lines:
        match = pattern.search(line)
        if match:
            gate, horse, index = match.groups()
            try:
                val = float(index)
                if 50.0 <= val <= 130.0: # ウマニティ指数の現実的な範囲
                    extracted_data.append({
                        "horse_name": horse.strip(),
                        "u_index": val
                    })
            except ValueError:
                continue
    return extracted_data

def parse_past5_ocr_text(text):
    """過去5走データテキストのパース"""
    results = []
    lines = [line.strip() for line in text.split("\n") if line.strip()]
    for line in lines:
        # 着順、タイム差、通過順、上りなどの数値を柔軟にパース
        tokens = line.replace(",", " ").split()
        if len(tokens) >= 2:
            results.append({
                "raw": line,
                "tokens": tokens
            })
    return results

