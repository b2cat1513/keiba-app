        if len(positive) < 5:
            suggestion = "データ不足"
        elif lift >= 10:
            suggestion = "重みを少し強める候補"
        elif lift <= -10:
            suggestion = "重みを弱める候補"
        else:
            suggestion = "現状維持候補"

