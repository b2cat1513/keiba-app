def parse_netkeiba_multi_line(raw_text):
    """
    netkeibaおよびウマニティの出馬表テキスト（複数行・コピペ形式）から
    1頭ずつのデータを高精度で一括抽出・展開するパース関数
    ※ウマニティのU指数にも対応
    """
    cleaned_horses = []
    lines = [line.strip() for line in raw_text.strip().split("\n") if line.strip()]
    
    current_horse = None
    
    for i, line in enumerate(lines):
        # 1. ウマニティの「U指数: 95.2」「U指数 95.2」「指数: 95.2」行の判定
        u_match = re.search(r'(?:U指数|指数)[\s:]*(\d{2,3}(?:\.\d+)?)', line, re.IGNORECASE)
        if u_match and current_horse:
            current_horse["u_idx"] = float(u_match.group(1))
            continue

        # 2. ウマニティ標準パターン（行内に馬番・馬名・性齢・斤量・騎手・体重・人気などがまとめられている形式）
        umanity_match = re.search(
            r'^(?:(?:\d{1,2})\s+)?(\d{1,2})\s+([ァ-ヴーa-zA-Z0-9]+)\s+([牡牝セ]\d+)\s*(\d{2}(?:\.\d+)?)\s*([\u4e00-\u9fa5ァ-ヴーa-zA-Z]+)', 
            line
        )
        if umanity_match:
            if current_horse: 
                cleaned_horses.append(current_horse)
            
            gate_num = int(umanity_match.group(1))
            horse_name = umanity_match.group(2)
            sex_age = umanity_match.group(3)
            jockey_weight = float(umanity_match.group(4))
            jockey_name = umanity_match.group(5)
            
            # 体重取得の試み
            w_match = re.search(r'(\d{3})\s*\(\s*([+-]?\d+)\s*\)', line)
            w_val = int(w_match.group(1)) if w_match else 480
            chg_val = int(w_match.group(2)) if w_match else 0
            
            # 人気取得の試み
            pop_match = re.search(r'(\d{1,2})番人気', line)
            pop_val = int(pop_match.group(1)) if pop_match else 10

            # 行内に直接U指数が含まれている場合の取得
            u_inline = re.search(r'(?:U指数|指数)[\s:]*(\d{2,3}(?:\.\d+)?)', line, re.IGNORECASE)
            u_val = float(u_inline.group(1)) if u_inline else 0.0

            current_horse = {
                "gate": gate_num,
                "frame": "内枠" if gate_num <= 8 else "外枠",
                "name": horse_name,
                "sex_age": sex_age,
                "jockey_weight": jockey_weight,
                "jockey": jockey_name,
                "weight": w_val,
                "change": chg_val,
                "pop": pop_val,
                "u_idx": u_val
            }
            continue

        # 3. netkeiba標準・複数行パターン
        base_match = re.search(r'([ァ-ヴーa-zA-Z0-9]+)\s+([牡牝セ]\d+).*?([\u4e00-\u9fa5ァ-ヴーa-zA-Z]+)\s+(\d{2}(?:\.\d+)?)', line)
        if base_match:
            if current_horse:
                cleaned_horses.append(current_horse)
                
            horse_name = base_match.group(1)
            sex_age = base_match.group(2)
            jockey_name = base_match.group(3)
            jockey_weight = float(base_match.group(4))
            
            current_horse = {
                "gate": None,
                "frame": "内枠",
                "name": horse_name,
                "sex_age": sex_age,
                "jockey_weight": jockey_weight,
                "jockey": jockey_name,
                "weight": 480,
                "change": 0,
                "pop": 10,
                "u_idx": 0.0
            }
            continue

        if current_horse:
            # U指数の単独・末尾検出
            u_solo = re.search(r'^\d{2,3}\.\d$', line)
            if u_solo and current_horse["u_idx"] == 0.0:
                current_horse["u_idx"] = float(u_solo.group(0))
                continue

            # 人気の判定（「11人気」「11番人気」等）
            pop_match = re.search(r'(\d{1,2})(?:人気|番人気)', line)
            if pop_match:
                current_horse["pop"] = int(pop_match.group(1))
                continue

            # 馬番の判定
            num_match = re.match(r'^(\d{1,2})$', line)
            if num_match:
                gate_num = int(num_match.group(1))
                current_horse["gate"] = gate_num
                current_horse["frame"] = "内枠" if gate_num <= 8 else "外枠"
                cleaned_horses.append(current_horse)
                current_horse = None
                continue
                
            # 体重・増減の判定
            weight_match = re.search(r'(\d{3})\s*\(\s*([+-]?\d+)\s*\)', line)
            if weight_match:
                current_horse["weight"] = int(weight_match.group(1))
                current_horse["change"] = int(weight_match.group(2))
                continue

    if current_horse:
        cleaned_horses.append(current_horse)

    for idx, h in enumerate(cleaned_horses):
        if h["gate"] is None:
            h["gate"] = idx + 1
            h["frame"] = "内枠" if (idx + 1) <= 8 else "外枠"

    return sorted(cleaned_horses, key=lambda x: x["gate"])

def safe_int_convert(value, default=0):
    """馬番等の安全な数値変換関数"""
    try:
        return int(value)
    except (ValueError, TypeError):
        return default

