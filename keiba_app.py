DB_PATH = Path("keiba_predictions.db")

def init_db():
    """予測履歴を保存するSQLiteテーブルの初期化"""
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS race_history (
            id TEXT PRIMARY KEY,
            created_at TEXT,
            race_name TEXT,
            course TEXT,
            track TEXT,
            race_data_json TEXT,
            result_json TEXT
        )
    """)
    conn.commit()
    conn.close()

def save_race_result(race_name, course, track, race_data, results):
    """予測結果の保存"""
    init_db()
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    rec_id = str(uuid.uuid4())
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    cursor.execute("""
        INSERT INTO race_history (id, created_at, race_name, course, track, race_data_json, result_json)
        VALUES (?, ?, ?, ?, ?, ?, ?)
    """, (
        rec_id, now, race_name, course, track,
        json.dumps(race_data, ensure_ascii=False),
        json.dumps(results, ensure_ascii=False)
    ))
    conn.commit()
    conn.close()

def load_race_history():
    """保存済みデータの取得"""
    init_db()
    conn = sqlite3.connect(DB_PATH)
    df = pd.read_sql_query("SELECT id, created_at, race_name, course, track FROM race_history ORDER BY created_at DESC", conn)
    conn.close()
    return df

