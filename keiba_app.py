st.header("📈 リアルタイム予想シミュレーター")

# 各種基本入力項目
course_list = list(COURSE_MASTER.keys())
selected_course = st.selectbox("予想対象コースを選択:", course_list)

# コース事典メモの自動表示
if selected_course in COURSE_MASTER:
    st.info(f"💡 【{selected_course} 特徴メモ】\n{COURSE_MASTER[selected_course]['note']}")

total_budget = st.number_input("想定総投資額 (円):", min_value=100, value=1000, step=100)

# ログ記録セクション
st.subheader("💾 実績シミュレーションログ")
with st.expander("過去のシミュレーションログを記録・管理する"):
    log_cols = st.columns(4)
    with log_cols[0]:
        res_course = st.selectbox("対象レースのコース:", course_list, key="log_course")
    with log_cols[1]:
        res_jiku = st.text_input("軸馬名:", value=st.session_state.get("last_predict_horse", ""))
    with log_cols[2]:
        is_hit = st.selectbox("軸馬の着順結果:", ["3着以内（的中）", ["4着以下（不的中）"]])
    with log_cols[3]:
        return_amt = st.number_input("実際の総払戻金 (円):", min_value=0, value=0, step=100)
        
    invest_amt = st.number_input("実際の総投資額 (円):", min_value=100, value=int(total_budget), step=100)

    if st.button("💾 この結果をシミュレーションログに公式記録する"):
        hit_flag = 1 if "3着以内" in is_hit else 0
        st.session_state["history_log"].append({
            "コース": res_course, "軸馬": res_jiku, "的中": hit_flag, "投資": invest_amt, "払戻": return_amt
        })
        st.toast("実績データを蓄積しました！")

if st.session_state["history_log"]:
    log_df = pd.DataFrame(st.session_state["history_log"])
    total_races = len(log_df)
    hits = log_df["的中"].sum()
    hit_rate = (hits / total_races) * 100 if total_races > 0 else 0
    total_invest = log_df["投資"].sum()
    total_return = log_df["払戻"].sum()
    recovery_rate = (total_return / total_invest) * 100 if total_invest > 0 else 0
    
    metrics_cols = st.columns(4)
    metrics_cols[0].metric("シミュレーション回数", f"{total_races} 回")
    metrics_cols[1].metric("軸馬3着内率 (的中率)", f"{hit_rate:.1f} %")
    metrics_cols[2].metric("総投資額", f"{total_invest:,} 円")
    metrics_cols[3].metric("トータル回収率", f"{recovery_rate:.1f} %")
    
    st.dataframe(log_df, use_container_width=True)
    if st.button("🗑️ ログをすべてクリア"):
        st.session_state["history_log"] = []
        st.rerun()
